#!/usr/bin/env bash
# Заполнение демо-БД реалистичными данными для питча салонам.
#
# В отличие от reset_demo.sh (который СНОСИТ БД и заново запускает init_db
# с пустой схемой) — этот скрипт сохраняет схему и миграции, стирает только
# user-данные и засевает «живую» картинку: 8 услуг, 3 мастера, 30 клиентов,
# ~70 записей за окно ±14 дней, ~12 отзывов.
#
# Когда использовать:
#   • Перед очной встречей с владельцем салона — чтобы экраны Сегодня/
#     Календарь/Статистика/Отзывы были не пустыми.
#   • После показа одному салону, перед следующим — чтобы цифры обнулились
#     и пересоздались (random.seed зафиксирован — картинка та же).
#
# Что делает:
#   1. Останавливает контейнер бота (redis оставляем — там FSM, не мешает).
#   2. Поднимает разовый контейнер из того же image, запускает в нём
#      tools/seed_demo.py --reset.
#   3. Стартует бот обратно.
#   4. Показывает последние логи бота для контроля.
#
# Что НЕ трогает:
#   • backups/ — там страховка.
#   • .env — токен/slug/admin_id остаются.
#   • schema БД, миграции, weekly_schedule, traffic_sources (дефолтные
#     desk/mirror/door остаются на месте, скрипт доливает Instagram/Рекомендация).
#
# ВНИМАНИЕ: tools/seed_demo.py имеет встроенный whitelist по TENANT_SLUG,
# поэтому случайный запуск на боевом инстансе НЕ сотрёт реальные данные —
# скрипт ругнётся и завершится с кодом 2.
set -euo pipefail

cd "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/.."

# Прокидываем все аргументы в seed_demo.py — так можно прокинуть --force,
# если демо-инстанс назван не из стандартного whitelist (см. DEMO_SLUGS
# в tools/seed_demo.py).
EXTRA_ARGS=("$@")

echo "→ Останавливаю бот..."
docker compose stop bot

echo "→ Заполняю демо-БД..."
# `run --rm` поднимает разовый контейнер с тем же image и volumes.
# `--reset` обязателен — если в БД уже что-то есть, скрипт без него ругается.
docker compose run --rm bot python tools/seed_demo.py --reset "${EXTRA_ARGS[@]}"

echo ""
echo "→ Запускаю бот обратно..."
docker compose start bot

echo "→ Жду 5 сек пока бот поднимется..."
sleep 5

echo ""
echo "=== Последние логи ==="
docker compose logs bot --tail 8 || true

echo ""
echo "✓ Демо засеяно. Открой /start от админа в боте — проверь «📊 Статистика»."
